/**
 * Scans public/map-assets/ and public/textures/ to generate a static manifest
 * of all map asset paths used by the export assembler.
 *
 * Run: pnpm build:export-manifest
 */
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, "..")
const OUTPUT = path.join(ROOT, "src/features/export/lib/map-asset-manifest.ts")

function walkDir(dir: string, base: string): string[] {
  const results: string[] = []
  if (!fs.existsSync(dir)) return results

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name)
    const relPath = path.join(base, entry.name).replace(/\\/g, "/")
    if (entry.isDirectory()) {
      results.push(...walkDir(fullPath, relPath))
    } else {
      results.push(relPath)
    }
  }
  return results
}

const fontFiles = walkDir(
  path.join(ROOT, "public/map-assets/fonts"),
  "map-assets/fonts"
)
const spriteFiles = walkDir(
  path.join(ROOT, "public/map-assets/sprites"),
  "map-assets/sprites"
)

const output = `// Auto-generated by scripts/generate-map-manifest.ts — do not edit
// Run: pnpm build:export-manifest

/** PBF glyph files for MapLibre text rendering */
export const MAP_FONT_PATHS: string[] = ${JSON.stringify(fontFiles, null, 2)}

/** Sprite JSON + PNG files for map icons */
export const MAP_SPRITE_PATHS: string[] = ${JSON.stringify(spriteFiles, null, 2)}

/** PMTiles file path */
export const PMTILES_PATH = "textures/globe.pmtiles"
`

// Ensure output directory exists
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true })
fs.writeFileSync(OUTPUT, output, "utf-8")

console.log(`Map manifest generated: ${fontFiles.length} fonts, ${spriteFiles.length} sprites`)
