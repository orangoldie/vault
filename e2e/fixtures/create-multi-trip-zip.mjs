function makeTripJson({ id, name, slug, startDate, endDate, steps }) {
  return JSON.stringify({
    id,
    name,
    slug,
    start_date: startDate,
    end_date: endDate,
    summary: `A trip called ${name}`,
    cover_photo: null,
    step_count: steps.length,
    total_km: 500,
    uuid: `uuid-${id}`,
    all_steps: steps,
  })
}

function makeStep({ id, tripId, name, slug, startTime, endTime }) {
  return {
    id,
    trip_id: tripId,
    display_name: name,
    description: `Visiting ${name}`,
    slug,
    start_time: startTime,
    end_time: endTime,
    location: {
      id,
      name,
      detail: "Somewhere",
      full_detail: `${name}, Somewhere`,
      country_code: "US",
      lat: 40.0,
      lon: -74.0,
      uuid: `loc-${id}`,
    },
    weather_condition: "sunny",
    weather_temperature: 25,
    uuid: `step-${id}`,
  }
}

